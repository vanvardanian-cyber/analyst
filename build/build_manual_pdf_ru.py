#!/usr/bin/env python3
"""Руководство по Листу 1 (Сезонность) — русская версия PDF."""
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib import colors
from reportlab.lib.styles import ParagraphStyle
from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                TableStyle, HRFlowable, KeepTogether)
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

FD = "/usr/share/fonts/truetype/dejavu/"
pdfmetrics.registerFont(TTFont("DV", FD + "DejaVuSans.ttf"))
pdfmetrics.registerFont(TTFont("DV-B", FD + "DejaVuSans-Bold.ttf"))
pdfmetrics.registerFont(TTFont("DV-I", FD + "DejaVuSans-Oblique.ttf"))
pdfmetrics.registerFontFamily("DV", normal="DV", bold="DV-B", italic="DV-I", boldItalic="DV-B")

ACCENT = colors.HexColor("#1F4E79"); GREY = colors.HexColor("#666666")
LIGHT = colors.HexColor("#EDF2F8"); BORDER = colors.HexColor("#C9D6E4")

st_title = ParagraphStyle("t", fontName="DV-B", fontSize=16, leading=20, textColor=ACCENT)
st_sub   = ParagraphStyle("s", fontName="DV", fontSize=9, leading=12.5, textColor=GREY)
st_h     = ParagraphStyle("h", fontName="DV-B", fontSize=11.5, leading=14.5, textColor=ACCENT, spaceBefore=12, spaceAfter=4)
st_b     = ParagraphStyle("b", fontName="DV", fontSize=9, leading=13, spaceAfter=5)
st_bul   = ParagraphStyle("u", parent=st_b, leftIndent=10, bulletIndent=2, spaceAfter=3)
st_cell  = ParagraphStyle("c", fontName="DV", fontSize=8, leading=11)
st_cellb = ParagraphStyle("cb", parent=st_cell, fontName="DV-B")
st_note  = ParagraphStyle("n", parent=st_b, textColor=GREY, fontSize=8, leading=11)

doc = SimpleDocTemplate("/home/claude/manual-sheet1-seasonality-RU.pdf", pagesize=A4,
                        leftMargin=18*mm, rightMargin=18*mm, topMargin=16*mm, bottomMargin=16*mm,
                        title="Лист 1 — Сезонность: руководство пользователя", author="easestore.de")
S = []
def h(t): S.append(Paragraph(t, st_h))
def p(t): S.append(Paragraph(t, st_b))
def bul(t): S.append(Paragraph(t, st_bul, bulletText="•"))
def tbl(header, rows, widths):
    data = [[Paragraph(x, st_cellb) for x in header]] + [[Paragraph(x, st_cell) for x in r] for r in rows]
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), ACCENT), ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, LIGHT]),
        ("GRID", (0,0), (-1,-1), 0.5, BORDER), ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("LEFTPADDING", (0,0), (-1,-1), 5), ("RIGHTPADDING", (0,0), (-1,-1), 5),
        ("TOPPADDING", (0,0), (-1,-1), 4), ("BOTTOMPADDING", (0,0), (-1,-1), 4),
    ]))
    S.append(t); S.append(Spacer(1, 6))

S.append(Paragraph("Лист 1 — Сезонность: руководство пользователя", st_title))
S.append(Spacer(1, 3))
S.append(Paragraph("Amazon.de Seller Workbook · внутренняя версия v1 · 19.08.2026 · будущий встроенный help-контент, easestore.de", st_sub))
S.append(Spacer(1, 6)); S.append(HRFlowable(width="100%", thickness=1, color=ACCENT)); S.append(Spacer(1, 6))
p("<b>На какой вопрос отвечает лист:</b> сезонен ли спрос в нише, когда начинается подъём и растёт ли категория "
  "вообще? Запускайте его <b>до</b> любых расчётов прибыли — 10 минут на нишу, и он отсеивает больше плохих "
  "кандидатов, чем любая другая проверка.")

h("1. Выберите правильное ключевое слово (это решает всё)")
p("Измеряйте <b>родительский запрос</b> — название товарной категории так, как его набирает покупатель, когда уже "
  "знает, <i>что</i> ему нужно, но ещё не выбрал, <i>какой именно</i> товар. Применяйте <b>тест удовлетворённости</b>: "
  "представьте человека, который набрал этот запрос, — будет ли он доволен, попав на ваш товар?")
tbl(["Его ответ", "Что это за запрос", "Для чего использовать"],
    [["Скорее нет — он искал что-то другое из этого отдела", "Слишком широкий («küche», «küchenzubehör»)", "Ни для чего"],
     ["Да — теперь выбирает между брендами", "<b>Родитель</b> («schubladen organizer küche»)", "<b>Этот лист</b>"],
     ["Да — и фраза уже описывает ваш точный вариант", "Ребёнок («besteckkasten bambus 30cm»)", "Заголовок листинга и PPC, позже"]],
    [62*mm, 62*mm, 50*mm])
bul("<b>Дети наследуют кривую родителя</b>, кроме случаев, когда добавленное слово меняет <i>причину покупки</i> "
    "(подарочные наборы, «kinder», сезонное применение). Такой ребёнок со своим драйвером требует отдельной "
    "проверки кривой и собственного тайминга поставки.")
bul("<b>Никогда не измеряйте листинг младше 18 месяцев.</b> График молодого листинга — это кривая запуска плюс "
    "сезон, и разделить их невозможно. Измеряйте категорию по данным, существовавшим до появления листинга.")

h("2. Получите данные (Helium 10 Cerebro)")
bul("Откройте Cerebro, вкладка <b>Analyze Keywords</b> (не <i>Find Keywords</i> — та ищет новые слова, это позже).")
bul("<b>Переключите флаг маркетплейса на Amazon.de.</b> По умолчанию часто стоит Amazon.com — данные США здесь бесполезны.")
bul("Введите родителя <b>плюс 2–3 его крупнейших детей одним запросом</b>, через запятую. Один запрос = один "
    "поисковый кредит независимо от числа слов в нём — группируйте по нише, чтобы экономить месячный лимит.")
bul("Нажмите иконку графика рядом с объёмом поиска, период — 2 года / всё время, экспорт через меню-гамбургер.")

h("3. Переведите недельные точки в месяцы")
p("История даёт ~4 точки на месяц. Каждая точка — недельный <i>замер месячного объёма</i> на эту дату, поэтому "
  "<b>усредняйте точки внутри календарного месяца. Никогда не суммируйте.</b> Суммирование считает один и тот же "
  "спрос четырежды и завышает месяцы с 5 точками на ~25% — фальшивые пики и ложная амплитуда.")
p("<b>Самопроверка:</b> свежая точка должна быть того же порядка, что и текущий объём поиска в основной таблице "
  "Cerebro. Тот же порядок = усреднение верно.")

h("4. Внесите данные (только жёлтые ячейки)")
bul("Окно данных может начинаться <b>с любого месяца</b> — лист описывает календарный профиль, а не календарный "
    "год. Единственное правило: <b>каждое значение идёт в строку своего календарного месяца.</b> Август 2024 — в "
    "строку Aug первого года; январь 2025 — в строку Jan первого года; август 2025 — в Aug второго года.")
bul("«Год 1» = более старые 12 месяцев, «Год 2» = свежие 12. В окне из 25 месяцев один лишний: "
    "<b>отбросьте текущий незавершённый месяц.</b>")
bul("<b>Проверка на здравый смысл:</b> приходится ли пик на месяц, логичный для товара в реальной жизни? Органайзеры "
    "пикуют в январе (новогоднее наведение порядка), вело-товары — летом. Пик в бессмысленном месяце почти всегда "
    "означает сдвиг строк.")

h("5. Прочитайте результаты")
tbl(["Показатель", "Смысл", "Пороги / правило"],
    [["<b>Амплитуда</b>", "Лучший месяц / худший месяц — форма года",
      "&lt;1,5 ровно · 1,5–2,5 умеренно · 2,5–4 сильно · &gt;4 односезонный товар (ловушка капитала для первого товара)"],
     ["<b>Доля топ-4 месяцев</b>", "Насколько концентрирован год",
      "&gt;60% = бизнес на четыре месяца, несущий расходы двенадцати"],
     ["<b>Месяц подъёма</b>", "Первый месяц, где индекс проходит 1,00 вверх (переход декабрь-январь учтён)",
      "Товар на складе за ~4 недели до него — уходит в Лист 2. Январский подъём даёт дату поставки в начале декабря (перегрузка Q4): цельтесь в середину ноября"],
     ["<b>YoY / направление</b>", "Растёт ли категория?",
      "&gt;+5% рост · −5…+5% ровно · −5…−15% остывает (проверить в Trends) · &lt;−15% падает (отказ)"],
     ["<b>Месяцев с данными</b>", "Предохранитель",
      "Вердикт не срабатывает, пока не заполнены все 12 месяцев; месяц с нулевым спросом = предупреждение об экстремальной сезонности"]],
    [30*mm, 56*mm, 88*mm])
p("Амплитуда и YoY отвечают на <b>разные вопросы</b>: амплитуда — форма года, YoY — поднимается прилив или падает. "
  "Ниша может пройти одно и провалить другое — пример ниже прошёл амплитуду (2,04) и провалил направление (−8,9%).")

h("6. Проверьте через Google Trends (2 минуты, бесплатно)")
p("Trends — независимое второе мнение о <b>форме и направлении</b>, но никогда об объёме (значения относительные, "
  "0–100 к пику внутри окна).")
bul("<b>Берите запрос шире, чем на Amazon.</b> Trends выборка всего Google; нишевая фраза из 3 слов лежит у порога "
    "шума и рисует рваную, ненадёжную линию. Уберите уточнение: «schubladen organizer», а не «schubladen organizer "
    "küche». Регион Германия, 5 лет.")
bul("<b>Игнорируйте плашку «+X% к прошлому периоду»</b> — она сравнивает с годами, когда термина почти не существовало.")
bul("<b>Читайте пики по годам.</b> Тот же пиковый месяц, что в Cerebro = форма подтверждена. Пики, снижающиеся год "
    "за годом = настоящий спад; бум, осевший на плато выше добумового уровня = нормализация, приемлемо.")
bul("<b>Проверка лексики.</b> Немецкая товарная лексика дрейфует (besteckkasten против organizer). В режиме "
    "сравнения Trends добавьте традиционный синоним. Падают оба = категория действительно остывает. Один держится, "
    "другой падает = сдвиг названия, а не потеря спроса — перепроверьте по выручке первой страницы в Xray "
    "(взгляд денег, а не слов).")

h("7. Примите решение")
tbl(["Ситуация", "Действие"],
    [["Ровная/умеренная амплитуда + ровное или растущее направление", "Пройдено. Дальше Лист 3 (юнит-экономика)"],
     ["Сильная амплитуда, подъём ещё достижим", "Лист 2: дата размещения заказа ещё в будущем?"],
     ["Односезонный товар или месяцы с нулевым спросом", "Отказ как первый товар"],
     ["Направление «остывает»", "Решают Trends + проверка лексики; входить только с сильным углом дифференциации"],
     ["Направление «падает»", "Отказ, если Trends не показывает явно временный провал"]],
    [95*mm, 79*mm])
p("Амплитуду, долю топ-4 и вердикт направления внесите в колонку ниши на Листе 5 (скоркарта).")

ex = [Paragraph("Разобранный пример (реальный прогон)", st_h),
      Paragraph("<i>schubladen organizer küche</i>, Amazon.de, 24 месяца до августа 2026: амплитуда <b>2,04</b> "
        "(умеренно, пройдено), доля топ-4 <b>41,6%</b> (пройдено), пик <b>январь</b> / минимум <b>июнь</b> — паттерн "
        "новогоднего наведения порядка, значит выравнивание строк верное. Подъём в <b>январе</b>: на складе к середине "
        "ноября, заказ примерно к сентябрю. Но YoY <b>−8,9%</b>, минус в 10 из 12 месяцев: ОСТЫВАЕТ. Trends за 5 лет "
        "(«schubladen organizer»): январские пики 73 → 100 (2023) → 92 → 68 → 55 — бум с вершиной в начале 2023 и "
        "ступенчатым снижением, сейчас на добумовом уровне. До проверки лексики против «besteckkasten» ниша "
        "<b>не проходит правило «ровно или растёт»</b>, несмотря на удобную сезонность. Это лист делает свою работу: "
        "амплитуда сказала «нормально», направление сказало «нет».", st_b)]
S.append(KeepTogether(ex))

h("Типичные ошибки (каждая даёт уверенно неверный ответ)")
for m in ["Измерять запрос-отдел («küchenzubehör») — бессмысленные спрос, конкуренция и кривая.",
          "Измерять свой точный вариант — слишком тонко; шум читается как сезонность.",
          "<b>Суммировать</b> недельные точки вместо усреднения.",
          "Вносить экспорт по порядку строк, а не по календарным месяцам (сдвигает всю кривую).",
          "Верить рваной линии Trends по фразе из 3 слов вместо расширения запроса.",
          "Читать плашку «+X%» в Trends как рост.",
          "Мерить амплитуду по BSR — ранги относительны и системно занижают сезонные колебания.",
          "Измерять листинг младше 18 месяцев вместо категории."]:
    bul(m)

S.append(Spacer(1, 8)); S.append(HRFlowable(width="100%", thickness=0.5, color=BORDER)); S.append(Spacer(1, 3))
S.append(Paragraph("Учебный материал, не финансовая консультация. Источники данных: Helium 10 Cerebro (Amazon.de), "
                   "Google Trends (DE, 5 лет), Amazon Product Opportunity Explorer для перекрёстной проверки. Метод: "
                   "классическая мультипликативная декомпозиция (Hyndman &amp; Athanasopoulos, otexts.com/fpp3).", st_note))

doc.build(S)
print("done")
